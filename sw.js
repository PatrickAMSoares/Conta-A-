// Service worker do Conta Aí — cache mínimo do app shell para funcionar offline.
// Estratégia network-first: sempre tenta a rede primeiro, só cai para o cache
// quando não há conexão. Isso garante que correções e atualizações cheguem
// aos usuários imediatamente quando online; o cache só existe como fallback.
const CACHE_NAME = 'conta-ai-shell-v1';
const APP_SHELL = ['./', './index.html', './manifest.json', './icon-192.png'];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then((cache) => cache.addAll(APP_SHELL))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((names) => Promise.all(
        names.filter((n) => n !== CACHE_NAME).map((n) => caches.delete(n))
      ))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;

  event.respondWith(
    fetch(req)
      .then((res) => {
        const copy = res.clone();
        caches.open(CACHE_NAME).then((cache) => cache.put(req, copy));
        return res;
      })
      .catch(() => caches.match(req).then((cached) => cached || caches.match('./index.html')))
  );
});
